import cosmosis


class PowerModule(cosmosis.ClassModule):
    # This parent class expects that the __init__ method is overridden,
    # matching the setup function in our first module.  
    def __init__(self, options):
        # In this class the options parameter has been trimmed to just be the options
        # specific to this module, so no funny 'cosmosis.options_section' is needed
        # when getting parameters
        self.exponent = options.get_double("exponent")
    
    # The execute method is exactly the same as the previous version
    def execute(self, block):
        coef  = block['power_module_coef', 'power_module_param']
        #print(f"PowerModule: block['poly', 'y']={block['poly', 'y']}, coef={coef}, exponent={self.exponent}")
        block['poly', 'y'] = (block['poly', 'y']*coef) ** self.exponent

# The parent class has a method called as_module which converts this to a module
def setup(config: cosmosis.datablock) -> PowerModule:
    """Setup hook for a CosmoSIS module.

    The returned object will be passed to the CosmoSIS execute hook.

    :param config: the datablock the configuration
    :returns: an instance of class PowerModule
    """
    #return Likelihood(config)
    instance = PowerModule.as_module("power")
    instance.setup(config)
    return instance


def execute(sample: cosmosis.datablock, instance: PowerModule) -> int:
    """Execute hook for a CosmoSIS module.

    Return 0 on success. The parameter `sample` represents the current MCMC sample;
    `instance` is the PowerModule object created by `setup`.

    :param sample: the sample generated by the sampler
    :param instance: the Likelihood object
    :returns: the status of the call to the module's execute function
    """
    return instance.execute(sample)


def cleanup(_) -> int:
    """Cleanup hook for a CosmoSIS module. This one has nothing to do.

    :returns: 0
    """
    return 0
